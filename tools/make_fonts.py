#!/usr/bin/env python3
"""JetBrains Mono TTF -> VLW smooth fonts for Seeed_GFX2, as C headers.

Run from the repo root:  python3 tools/make_fonts.py
Writes heysticky/src/fonts/<name>.h and heysticky/src/fonts/fonts.h.

VLW layout (see libs/Seeed_GFX2/src/font/Font_Smooth.cpp), all int32 big-endian:
  header: count, 11, size, 0, ascent, descent
  per glyph: unicode, height, width, xAdvance, dY (top above baseline), dX, 0
  then 8-bit alpha bitmaps, row by row.
Spaces: the library never looks up U+0020 and guesses its width, so we ship U+00A0
with the real monospace advance and ui.h draws every space as U+00A0.
"""
import struct
import unicodedata
from pathlib import Path
from PIL import Image, ImageDraw, ImageFont

ROOT = Path(__file__).resolve().parent.parent
OUT = ROOT / "heysticky" / "src" / "fonts"
INK_THRESHOLD = 128  # alpha 0..255 -> ink; calibration knob for stroke weight on the panel

ASCII = "".join(chr(c) for c in range(0x21, 0x7F))
VI_BASES = "aăâeêioôơuưyAĂÂEÊIOÔƠUƯY"
VI_TONES = ["", "̀", "́", "̉", "̃", "̣"]  # none, huyền, sắc, hỏi, ngã, nặng
VIETNAMESE = "đĐ" + "".join(unicodedata.normalize("NFC", b + t) for b in VI_BASES for t in VI_TONES)
EXTRA = " °·…“”‘’–—•●×"
TEXT = ASCII + VIETNAMESE + EXTRA

# name: (style, px size, characters)
FONTS = {
    "B20": ("Bold", 20, TEXT),
    "R20": ("Regular", 20, TEXT),
    "B25": ("Bold", 25, TEXT),
    "B26": ("Bold", 26, TEXT),
    "X25": ("ExtraBold", 25, TEXT),
    "R25": ("Regular", 25, TEXT),
    "R30": ("Regular", 30, TEXT),
    "B35": ("Bold", 35, TEXT),
    "X30": ("ExtraBold", 30, TEXT),
    "X32": ("ExtraBold", 32, TEXT),
    "X28": ("ExtraBold", 28, "0123456789.,-°%CF "),
    "X48": ("ExtraBold", 48, "0123456789-°CF "),
    "X120": ("ExtraBold", 120, "0123456789:- "),
    "X34": ("ExtraBold", 34, "0123456789: "),
    "X40": ("ExtraBold", 40, "Delete task?Xoá việc này?Delete note?Xoá ghi chú?"),
}


def vlw(style, size, chars):
    font = ImageFont.truetype(str(ROOT / "fonts" / f"JetBrainsMono-{style}.ttf"), size)
    ascent, descent = font.getmetrics()
    space_adv = round(font.getlength(" "))
    records, bitmaps = [], []
    for ch in sorted(set(chars), key=ord):
        if ch == " ":
            records.append(struct.pack(">7i", ord(ch), 0, 0, space_adv, 0, 0, 0))
            continue
        x0, y0, x1, y1 = font.getbbox(ch, anchor="ls")
        w, h = x1 - x0, y1 - y0
        img = Image.new("L", (max(w, 1), max(h, 1)), 0)
        ImageDraw.Draw(img).text((-x0, -y0), ch, font=font, fill=255, anchor="ls")
        # 1-bit panel: the library maps any non-black pixel to white, so anti-aliased edges
        # would vanish and thin the strokes. Pre-threshold at 50% coverage instead.
        img = img.point(lambda a: 255 if a >= INK_THRESHOLD else 0)
        adv = round(font.getlength(ch))
        assert w <= 255 and h <= 255 and adv <= 255 and -128 <= x0 <= 127, (ch, w, h, adv, x0)
        records.append(struct.pack(">7i", ord(ch), h, w, adv, -y0, x0, 0))
        bitmaps.append(img.tobytes() if w and h else b"")
    head = struct.pack(">6i", len(records), 11, size, 0, ascent, descent)
    return head + b"".join(records) + b"".join(bitmaps), ascent, descent


def main():
    OUT.mkdir(parents=True, exist_ok=True)
    index = ["// Generated by tools/make_fonts.py - do not edit.", "#pragma once", "#include <stdint.h>",
             "struct Font { const uint8_t *data; uint8_t asc, desc; };"]
    total = 0
    for name, (style, size, chars) in FONTS.items():
        data, asc, desc = vlw(style, size, chars)
        total += len(data)
        rows = ",\n".join(", ".join(f"0x{b:02x}" for b in data[i:i + 24]) for i in range(0, len(data), 24))
        (OUT / f"{name}.h").write_text(
            f"// JetBrains Mono {style} {size}px, {len(set(chars))} glyphs. Generated by tools/make_fonts.py.\n"
            f"#pragma once\n#include <pgmspace.h>\nconst uint8_t {name}_vlw[] PROGMEM = {{\n{rows}\n}};\n")
        index += [f'#include "{name}.h"', f"inline const Font F_{name} = {{{name}_vlw, {asc}, {desc}}};"]
        print(f"{name:5s} {style:9s} {size:3d}px  {len(set(chars)):3d} glyphs  asc={asc} desc={desc}  {len(data) / 1024:6.1f} KB")
    (OUT / "fonts.h").write_text("\n".join(index) + "\n")
    print(f"total {total / 1024:.0f} KB")


if __name__ == "__main__":
    main()
