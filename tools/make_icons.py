#!/usr/bin/env python3
"""Figma icon PNGs (tools/icons/*.png, exported at 1x) -> 1-bit bitmaps for drawBitmap().

Run from the repo root:  python3 tools/make_icons.py
Writes heysticky/src/icons.h. Rows are MSB-first, padded to whole bytes.
Threshold 64 keeps Figma's ~1.5 px strokes continuous on the 1-bit panel.
"""
from pathlib import Path
from PIL import Image

ROOT = Path(__file__).resolve().parent.parent
THRESHOLD = 64  # alpha 0..255; calibration knob for stroke thickness


def pack(png):
    im = Image.open(png).convert("RGBA")
    w, h = im.size
    out = bytearray()
    for y in range(h):
        row = 0
        for x in range(((w + 7) // 8) * 8):
            r, g, b, a = im.getpixel((x, y)) if x < w else (0, 0, 0, 0)
            ink = a >= THRESHOLD  # any opaque pixel is ink; the colour is chosen when drawing
            row = (row << 1) | ink
            if x % 8 == 7:
                out.append(row)
                row = 0
    return w, h, bytes(out)


def main():
    lines = ["// Generated by tools/make_icons.py from Figma exports - do not edit.", "#pragma once",
             "#include <pgmspace.h>", "struct Icon { const uint8_t *bits; uint8_t w, h; };"]
    for png in sorted((ROOT / "tools" / "icons").glob("*.png")):
        w, h, data = pack(png)
        name = png.stem.upper()
        hexs = ", ".join(f"0x{b:02x}" for b in data)
        lines += [f"const uint8_t {name}_bits[] PROGMEM = {{{hexs}}};",
                  f"inline const Icon ICON_{name} = {{{name}_bits, {w}, {h}}};"]
        print(f"{name:14s} {w}x{h}")
    (ROOT / "heysticky" / "src" / "icons.h").write_text("\n".join(lines) + "\n")


if __name__ == "__main__":
    main()
